import assert from 'node:assert/strict';
import { adaptiveContrastColor, applyXpsContrastXml, createContrastPage } from '../dist/render/contrast.js';

const dark = { contrastMode: 'adaptive', background: '#05070d' };
const light = { contrastMode: 'adaptive', background: '#ffffff' };
assert.notEqual(adaptiveContrastColor('#000000', dark), '#000000');
assert.equal(adaptiveContrastColor('#ff0000', dark), '#ff0000');
assert.equal(adaptiveContrastColor('#000000', light), '#000000');
assert.notEqual(adaptiveContrastColor('#ffffff', light), '#ffffff');
assert.equal(adaptiveContrastColor('#000000', { ...dark, contrastMode: 'preserve' }), '#000000');
assert.match(adaptiveContrastColor('#80000000', dark), /, 0\.5019607843137255\)$/);
assert.equal(adaptiveContrastColor('Transparent', dark), 'Transparent');
assert.equal(adaptiveContrastColor('{StaticResource Ink}', dark), '{StaticResource Ink}');
const points = [0, 0, 10, 10];
const page = { kind: 'w2d-text', primitives: [{ type: 'polyline', points }, { type: 'polygon', points, fill: '#000000' }, { type: 'text', text: 'A' }] };
const before = JSON.stringify(page);
const adapted = createContrastPage(page, dark);
assert.equal(JSON.stringify(page), before);
assert.equal(adapted.primitives[0].points, points);
assert.notEqual(adapted.primitives[0].stroke, '#000000');
assert.equal(adapted.primitives[1].stroke, undefined);
assert.ok(adapted.primitives[2].fill);
assert.equal(createContrastPage(page, dark), adapted);
assert.notEqual(createContrastPage(page, light), adapted);
const xml = '<FixedPage><Path Stroke="#000000" Fill="#FFFF0000" Opacity="0.4"/><ImageBrush ImageSource="image.png"/><SolidColorBrush Color="#FF000000"/></FixedPage>';
const converted = applyXpsContrastXml(xml, dark);
assert.notEqual(converted, xml);
assert.match(converted, /Fill="#FFFF0000"/);
assert.match(converted, /Opacity="0.4"/);
assert.match(converted, /ImageSource="image.png"/);
assert.equal(applyXpsContrastXml(xml, { contrastMode: 'preserve' }), xml);
console.log('Native DWF/XPS contrast, source immutability, alpha and cache policy verified.');
